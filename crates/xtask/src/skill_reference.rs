const BANNER: &str = "<!-- Generated by `cargo xtask gen-skill-reference` from the crate and the spec. \
Do not edit: CI fails on drift (docs/skills.md §7). Regenerate after a change to spec/ or to \
the crate facts it cites. -->\n\n";

/// Generate, then write or compare.
pub fn run(root: &Path, check: bool) -> Result<bool> {
    let files = generate(root)?;
    if !check {
        for (path, content) in &files {
            let target = root.join(path);
            if let Some(parent) = target.parent() {
                fs::create_dir_all(parent)?;
            }
            fs::write(&target, content).with_context(|| format!("writing {path}"))?;
        }
        println!(
            "gen-skill-reference: wrote {} files under app-skills/*/reference/",
            files.len()
        );
        return Ok(true);
    }
    let mut drift = Vec::new();
    for (path, content) in &files {
        match fs::read_to_string(root.join(path)) {
            Ok(existing) if normalize(&existing) == *content => {}
            Ok(_) => drift.push(format!("{path}: differs from what the generator writes")),
            Err(_) => drift.push(format!("{path}: missing")),
        }
    }
    for path in crate::repo::files(root)? {
        if path.starts_with("app-skills/")
            && path.contains("/reference/")
            && !files.contains_key(&path)
        {
            drift.push(format!("{path}: not written by the generator"));
        }
    }
    if drift.is_empty() {
        println!(
            "gen-skill-reference: {} files match what the crate and the spec generate",
            files.len()
        );
        return Ok(true);
    }
    for line in &drift {
        eprintln!("gen-skill-reference: {line}");
    }
    eprintln!(
        "\ngen-skill-reference: {} files drifted. A change to spec/ or to the crate that is not \
         reflected in app-skills/ is an incomplete change (docs/skills.md §7): run \
         `cargo xtask gen-skill-reference` and commit the result.",
        drift.len()
    );
    Ok(false)
}

fn normalize(text: &str) -> String {
    text.strip_prefix('\u{feff}')
        .unwrap_or(text)
        .replace("\r\n", "\n")
}

/// Every generated file, by repository-relative path.
fn generate(root: &Path) -> Result<BTreeMap<String, String>> {
    let mut files: BTreeMap<String, String> = BTreeMap::new();
    let mut put = |skill: &str, name: &str, body: String| {
        files.insert(
            format!("app-skills/{skill}/reference/{name}"),
            format!("{BANNER}{body}"),
        );
    };

    // privatium-overview
    put(
        "privatium-overview",
        "lint-rules.md",
        lint_rules(RULES.iter()),
    );
    put("privatium-overview", "glossary.md", glossary(root)?);
    put(
        "privatium-overview",
        "decision-tree.md",
        format!(
            "# Tiers and modes\n\nFrom `spec/app-contract.md §1` and `§2`, the contract's own words.\n\n{}\n{}",
            section(root, "spec/app-contract.md", "1")?,
            section(root, "spec/app-contract.md", "2")?
        ),
    );

    // privatium-tier1-lua
    put("privatium-tier1-lua", "pv-api.md", pv_api(root)?);
    put(
        "privatium-tier1-lua",
        "lsp-syntax.md",
        format!(
            "# LSP templates\n\nFrom `spec/lua-api.md §4`, the contract's own words.\n\n{}",
            section(root, "spec/lua-api.md", "4")?
        ),
    );
    let tier1_rules: Vec<RuleId> = RULES
        .iter()
        .map(|r| r.id)
        .filter(|id| !matches!(id, RuleId::PV206 | RuleId::PV304))
        .collect();
    put(
        "privatium-tier1-lua",
        "anti-patterns.md",
        anti_patterns(root, "Tier 1", &tier1_rules)?,
    );

    // privatium-tier2-web
    put("privatium-tier2-web", "pv-js.md", pv_js(root)?);
    put(
        "privatium-tier2-web",
        "endpoints.md",
        format!(
            "# The data API\n\nFrom `spec/data-api.md`, the contract's own words.\n\n{}\n{}\n{}\n{}\n{}",
            section(root, "spec/data-api.md", "1")?,
            section(root, "spec/data-api.md", "2")?,
            section(root, "spec/data-api.md", "3")?,
            section(root, "spec/data-api.md", "4")?,
            section(root, "spec/data-api.md", "7")?
        ),
    );
    put("privatium-tier2-web", "permissions.md", permissions(root)?);
    let tier2_rules: Vec<RuleId> = RULES
        .iter()
        .map(|r| r.id)
        .filter(|id| {
            !matches!(
                id,
                RuleId::PV106
                    | RuleId::PV107
                    | RuleId::PV201
                    | RuleId::PV202
                    | RuleId::PV203
                    | RuleId::PV204
                    | RuleId::PV302
                    | RuleId::PV303
                    | RuleId::PV306
                    | RuleId::PV307
                    | RuleId::PV308
                    | RuleId::PV403
                    | RuleId::PV405
                    | RuleId::PV407
                    | RuleId::PV503
                    | RuleId::PV505
                    | RuleId::PV506
            )
        })
        .collect();
    put(
        "privatium-tier2-web",
        "anti-patterns.md",
        anti_patterns(root, "Tier 2", &tier2_rules)?,
    );

    // privatium-tier3-rust
    put("privatium-tier3-rust", "api.md", rust_api(root)?);

    // privatium-accessibility
    put("privatium-accessibility", "rules.md", accessibility(root)?);

    // privatium-security
    put("privatium-security", "rules.md", security(root)?);

    // privatium-games
    put(
        "privatium-games",
        "isolation.md",
        format!(
            "# Games, engines and cross-origin isolation\n\nFrom `docs/frameworks.md §5`, plus what the loader says when an app asks for isolation in host mode.\n\n{}\n## What the loader says\n\n```\n{}\n```\n",
            section(root, "docs/frameworks.md", "5")?,
            ManifestError::CrossOriginIsolatedInHostMode
        ),
    );

    // Every skill: an index of its reference files.
    let mut by_skill: BTreeMap<String, Vec<String>> = BTreeMap::new();
    for path in files.keys() {
        let mut parts = path.split('/');
        let (_, skill, _, name) = (parts.next(), parts.next(), parts.next(), parts.next());
        if let (Some(skill), Some(name)) = (skill, name) {
            by_skill
                .entry(skill.to_owned())
                .or_default()
                .push(name.to_owned());
        }
    }
    for (skill, names) in by_skill {
        let list: String = names.iter().map(|n| format!("- `{n}`\n")).collect();
        files.insert(
            format!("app-skills/{skill}/reference/README.md"),
            format!(
                "{BANNER}# Reference\n\nThe pinned reference for `{skill}` (docs/skills.md §3): generated from \
                 `privatium-core` {} (`{PROTOCOL}`, `api = {SUPPORTED_API}`) and the specification at the \
                 same commit, so what is written here is what this version implements.\n\n{list}\n\
                 Regenerate with `cargo xtask gen-skill-reference`; `--check` is the CI gate.\n",
                privatium_core::VERSION
            ),
        );
    }
    Ok(files)
}

/// The numbered section of a spec document, heading included, up to the next heading of
/// the same or a higher level.
fn section(root: &Path, path: &str, number: &str) -> Result<String> {
    let text = crate::repo::read_normalized(&root.join(path))?;
    let lines: Vec<&str> = text.lines().collect();
    let start = lines
        .iter()
        .position(|line| line.starts_with('#') && spec_ref::heading_is(line, number))
        .with_context(|| format!("{path}: no heading numbered §{number}"))?;
    let level = lines[start].chars().take_while(|c| *c == '#').count();
    let mut end = lines.len();
    for (i, line) in lines.iter().enumerate().skip(start + 1) {
        let this = line.chars().take_while(|c| *c == '#').count();
        if this > 0 && this <= level && line[this..].starts_with(' ') {
            end = i;
            break;
        }
    }
    let mut body = lines[start..end].join("\n");
    while body.ends_with("\n---") || body.ends_with('\n') {
        body = body.trim_end_matches("---").trim_end().to_owned();
    }
    Ok(format!("{body}\n"))
}

fn escape_cell(text: &str) -> String {
    text.replace('|', "\\|")
}

fn rules_table<'a>(rules: impl Iterator<Item = &'a Rule>, criteria: bool) -> String {
    let mut out = String::new();
    if criteria {
        out.push_str(
            "| ID | Severity | Rule | WCAG 2.2 | Reads | Spec |\n|---|---|---|---|---|---|\n",
        );
    } else {
        out.push_str("| ID | Severity | Rule | Reads | Spec |\n|---|---|---|---|---|\n");
    }
    for rule in rules {
        if criteria {
            out.push_str(&format!(
                "| `{}` | {} | {} | {} | {} | `{}` |\n",
                rule.id,
                rule.severity,
                escape_cell(rule.title),
                rule.criterion.unwrap_or("—"),
                escape_cell(rule.reads),
                rule.spec
            ));
        } else {
            out.push_str(&format!(
                "| `{}` | {} | {} | {} | `{}` |\n",
                rule.id,
                rule.severity,
                escape_cell(rule.title),
                escape_cell(rule.reads),
                rule.spec
            ));
        }
    }
    out
}

fn lint_rules<'a>(rules: impl Iterator<Item = &'a Rule> + Clone) -> String {
    let mut out = String::from(
        "# Lint rules\n\nThe rule table of `privatium lint` as the crate holds it — `spec/cli.md §5.1`'s \
         rules with their stable IDs, severities, what the linter reads for each, and the section \
         every finding cites. `privatium lint apps/<slug>` exits 3 on findings; `--format json` \
         writes one object per finding with `id`, `severity`, `file`, `line`, `message`, `fix` and \
         `spec` (`§5.2`); `--severity error|warn|info` is the floor; `--fix` applies the mechanical \
         corrections of `§5.3` — a literal mount path to `url()`, `focusable=\"false\"` on an inline icon \
         — and nothing else.\n\n",
    );
    for class in [
        Class::Contract,
        Class::Security,
        Class::Correctness,
        Class::Accessibility,
        Class::Portability,
    ] {
        out.push_str(&format!("## {}\n\n", class.as_str()));
        out.push_str(&rules_table(
            rules.clone().filter(|r| r.class == class),
            class == Class::Accessibility,
        ));
        out.push('\n');
    }
    out
}

fn glossary(root: &Path) -> Result<String> {
    let slugs: String = RESERVED_SLUGS
        .iter()
        .map(|s| format!("`{s}`"))
        .collect::<Vec<_>>()
        .join(", ");
    let prefixes: String = FRAMEWORK_PREFIXES
        .iter()
        .map(|p| format!("`{p}`"))
        .collect::<Vec<_>>()
        .join(", ");
    Ok(format!(
        "# Glossary\n\n{}\n## Facts from the crate\n\n\
         | Fact | Value |\n|---|---|\n\
         | Protocol | `{PROTOCOL}` |\n\
         | App contract | `api = {SUPPORTED_API}` |\n\
         | Reserved slugs | {slugs} |\n\
         | Framework route prefixes (shadow a solo app's routes) | {prefixes} |\n\
         | Bootstrap Icons | {} ({} icons) |\n\
         | Tiers | {} |\n",
        section(root, "spec/protocol.md", "1")?,
        icons::version(),
        icons::count(),
        [Tier::Lua, Tier::Web, Tier::Rust]
            .iter()
            .map(|t| format!(
                "`{t}`{}",
                t.required_file()
                    .map_or(String::new(), |f| format!(" (requires `{f}`)"))
            ))
            .collect::<Vec<_>>()
            .join(", ")
    ))
}

