/// Which file of a fixture shows the rule. First existing wins.
fn primary_files(id: RuleId) -> &'static [&'static str] {
    match id {
        RuleId::PV101
        | RuleId::PV102
        | RuleId::PV103
        | RuleId::PV104
        | RuleId::PV105
        | RuleId::PV205
        | RuleId::PV501
        | RuleId::PV502
        | RuleId::PV503 => &["app.toml"],
        RuleId::PV106 | RuleId::PV107 => &["schema.sql"],
        RuleId::PV208 => &["sample/seed.jsonl"],
        RuleId::PV202
        | RuleId::PV204
        | RuleId::PV401
        | RuleId::PV402
        | RuleId::PV403
        | RuleId::PV405
        | RuleId::PV407 => &["views/index.lsp"],
        RuleId::PV404 => &["views/index.lsp", "views/_board.lsp"],
        RuleId::PV406 => &["static/app.css"],
        RuleId::PV206 | RuleId::PV207 | RuleId::PV304 => &["web/app.js"],
        RuleId::PV504 => &["web/index.html", "web/app.js"],
        _ => &["app.lua"],
    }
}

fn fence_language(path: &str) -> &'static str {
    match path.rsplit_once('.').map(|(_, ext)| ext) {
        Some("lua") => "lua",
        Some("sql") => "sql",
        Some("lsp" | "html") => "html",
        Some("toml") => "toml",
        Some("js") => "js",
        Some("css") => "css",
        Some("jsonl") => "json",
        _ => "",
    }
}

/// The file without its header block.
fn strip_header(path: &str, text: &str) -> String {
    let text = normalize(text);
    if path.ends_with(".lsp") {
        if let Some(end) = text.find("--?>") {
            return text[end + 4..].trim_start_matches('\n').to_owned();
        }
        return text;
    }
    if path.ends_with(".css") {
        if let Some(end) = text.find("*/") {
            return text[end + 2..].trim_start_matches('\n').to_owned();
        }
        return text;
    }
    let prefix = match path.rsplit_once('.').map(|(_, ext)| ext) {
        Some("lua" | "sql") => "--",
        Some("js") => "//",
        Some("toml") => "#",
        _ => return text,
    };
    let mut lines = text.lines().peekable();
    while lines.peek().is_some_and(|l| l.starts_with(prefix)) {
        lines.next();
    }
    let rest: Vec<&str> = lines.collect();
    rest.join("\n").trim_start_matches('\n').to_owned() + "\n"
}

/// The app folder of a fixture.
fn fixture_app(root: &Path, kind: &str, id: RuleId) -> Result<std::path::PathBuf> {
    let dir = root.join("apps").join("_lint").join(kind).join(id.as_str());
    let mut apps: Vec<_> = fs::read_dir(&dir)
        .with_context(|| format!("{}: no {kind} fixture", dir.display()))?
        .flatten()
        .map(|e| e.path())
        .filter(|p| p.join("app.toml").is_file())
        .collect();
    apps.sort();
    apps.into_iter()
        .next()
        .with_context(|| format!("{}: holds no app", dir.display()))
}

fn anti_patterns(root: &Path, tier: &str, ids: &[RuleId]) -> Result<String> {
    let mut out = format!(
        "# Anti-patterns — {tier}\n\nWrong code beside right code (docs/skills.md §3), from the \
         linter's own corpus under `apps/_lint/`: for each rule the file that fails it and the file \
         that passes it, headers stripped. `privatium lint` reports the left column and accepts the \
         right.\n\n"
    );
    for id in ids {
        let rule = privatium_core::lint::rule(*id);
        let fail = fixture_app(root, "fail", *id)?;
        let pass = fixture_app(root, "pass", *id)?;
        let pick = |app: &Path| -> Option<(String, String)> {
            primary_files(*id).iter().find_map(|rel| {
                let path = app.join(rel);
                fs::read_to_string(&path).ok().map(|text| {
                    let shown = path
                        .strip_prefix(root)
                        .map(|p| p.to_string_lossy().replace('\\', "/"))
                        .unwrap_or_default();
                    (shown, strip_header(rel, &text))
                })
            })
        };
        let (fail_path, fail_text) = pick(&fail)
            .with_context(|| format!("{}: no primary file for {}", fail.display(), id))?;
        let (pass_path, pass_text) = pick(&pass)
            .with_context(|| format!("{}: no primary file for {}", pass.display(), id))?;
        out.push_str(&format!(
            "## `{id}` — {}\n\n{} · `{}`\n\n**Wrong** (`{fail_path}`):\n\n```{}\n{}```\n\n**Right** (`{pass_path}`):\n\n```{}\n{}```\n\n",
            escape_cell(rule.title),
            rule.severity,
            rule.spec,
            fence_language(&fail_path),
            fail_text,
            fence_language(&pass_path),
            pass_text,
        ));
    }
    Ok(out)
}
